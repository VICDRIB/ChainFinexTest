// ── I18N ENGINE ────────────────────────────────────────────────────────────────
let currentLang = 'en';

export function detectLanguage() {
  const saved = localStorage.getItem('ChainFinex_lang');
  if (saved && SUPPORTED_LANGUAGES[saved]) return saved;

  const browserLang = navigator.language?.split('-')[0]?.toLowerCase();
  if (browserLang && SUPPORTED_LANGUAGES[browserLang]) return browserLang;

  return 'en';
}

export function setLanguage(lang) {
  if (!SUPPORTED_LANGUAGES[lang]) lang = 'en';
  currentLang = lang;
  localStorage.setItem('ChainFinex_lang', lang);

  // Update document direction for RTL languages
  document.documentElement.dir = SUPPORTED_LANGUAGES[lang].dir;
  document.documentElement.lang = lang;

  // Dispatch event so components can re-render
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

export function t(key) {
  return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key])
    || (TRANSLATIONS.en[key])
    || key;
}

export function getCurrentLang() { return currentLang; }
export function initI18n() {
  const lang = detectLanguage();
  setLanguage(lang);
  return lang;
}
